-- Migration 008: Entity dossiers — long-form, cited articles over many stories
--
-- A story is a single document; a "dossier" is a synthesized long-form piece
-- about one entity (vendor or model family) built from the stories we have
-- already ingested and summarized. It reads like a publication article: a hero,
-- a table of contents, sectioned prose, real extracted quotes, and a sourced
-- facts table — with every claim traceable back to the underlying stories.
--
-- `blocks` holds the article as typed blocks rather than one flat string, so the
-- renderer can lay out headings, paragraphs, lists, quotes, and the facts table
-- without ever injecting third-party HTML:
--   { "type": "heading",   "level": 2 | 3, "text": "…" }
--   { "type": "paragraph", "text": "… [1] …" }        -- [n] cites `story_ids`
--   { "type": "list",      "items": ["…"] }
--   { "type": "quote",     "text": "…", "index": 4 }  -- index into `story_ids`
--   { "type": "keyfacts",  "facts": [{ "label": "…", "value": "…", "index": 4 }] }
--
-- `story_ids` is the ordered source list the [n] markers refer to, so a dossier
-- can never cite something it wasn't given (the renderer links each marker to
-- the story page).
--
-- Dossiers are generated by the ingest job / a dedicated cron route using the
-- same optional LLM tier as story summaries; with no key configured nothing is
-- generated and the table simply stays empty.
--
-- Safe to run after 001-007. Idempotent.

CREATE TABLE IF NOT EXISTS dossiers (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  slug TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  subtitle TEXT,
  blocks JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(blocks) = 'array'),
  story_ids UUID[] NOT NULL DEFAULT '{}',
  llm_model TEXT,
  generated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_dossiers_generated_at ON dossiers (generated_at DESC);

DROP TRIGGER IF EXISTS update_dossiers_updated_at ON dossiers;
CREATE TRIGGER update_dossiers_updated_at
  BEFORE UPDATE ON dossiers
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

COMMENT ON TABLE dossiers IS
  'Long-form, cited articles synthesized from many stories about one entity (vendor or model family).';
COMMENT ON COLUMN dossiers.slug IS
  'Stable entity slug (matches the entity registry), e.g. "anthropic".';
COMMENT ON COLUMN dossiers.subtitle IS
  'Standfirst shown under the title in the hero.';
COMMENT ON COLUMN dossiers.blocks IS
  'Ordered typed content blocks (heading/paragraph/list/quote/keyfacts) rendered by the dossier renderer.';
COMMENT ON COLUMN dossiers.story_ids IS
  'Ordered source stories; [n] citation markers in blocks are 1-based indexes into this array.';
COMMENT ON COLUMN dossiers.llm_model IS
  'Model id that generated the dossier; NULL means it predates the current LLM tier.';

-- Public read: every dossier is generated, published content. Writes stay with
-- the service role (the generation job) and, like stories, editors.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_tables WHERE tablename = 'dossiers' AND rowsecurity = true
  ) THEN
    ALTER TABLE dossiers ENABLE ROW LEVEL SECURITY;
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'dossiers' AND policyname = 'public_read_dossiers') THEN
    CREATE POLICY public_read_dossiers ON dossiers FOR SELECT TO public USING (true);
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'dossiers' AND policyname = 'editors_read_dossiers') THEN
    CREATE POLICY editors_read_dossiers ON dossiers FOR SELECT TO authenticated USING (is_editor());
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'dossiers' AND policyname = 'editors_insert_dossiers') THEN
    CREATE POLICY editors_insert_dossiers ON dossiers FOR INSERT TO authenticated WITH CHECK (is_editor());
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'dossiers' AND policyname = 'editors_update_dossiers') THEN
    CREATE POLICY editors_update_dossiers ON dossiers FOR UPDATE TO authenticated USING (is_editor()) WITH CHECK (is_editor());
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'dossiers' AND policyname = 'editors_delete_dossiers') THEN
    CREATE POLICY editors_delete_dossiers ON dossiers FOR DELETE TO authenticated USING (is_editor());
  END IF;
END $$;

